export const todayShellLogic = kea<todayShellLogicType>([
    path(['layout', 'today', 'todayShellLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], navigationLogic, ['mobileLayout']],
        actions: [router, ['locationChanged']],
    })),
    actions({
        pickPane: (pane: TodayRailPane) => ({ pane }),
        goBackOnMobile: true,
        setMobilePages: (pages: TodayMobilePage[]) => ({ pages }),
        setMobileSidebarOpen: (open: boolean) => ({ open }),
        setSidebarOpen: (open: boolean) => ({ open }),
        setSidebarWidth: (width: number) => ({ width }),
        toggleSidebar: true,
    }),
    windowValues(() => ({
        mobileNavLayout: (window: Window) => window.innerWidth < TODAY_MOBILE_NAV_MAX_WIDTH,
    })),
    reducers({
        // The last pane picked on the rail, or reached through a route that belongs to one, stays open on other pages.
        pickedPane: [
            null as TodayRailPane | null,
            {
                pickPane: (_, { pane }) => pane,
                locationChanged: (state, { pathname }) => railPaneForPath(pathname) ?? state,
            },
        ],
        sidebarOpen: [
            true,
            { persist: true },
            {
                setSidebarOpen: (_, { open }) => open,
            },
        ],
        mobileSidebarOpen: [
            false,
            {
                setMobileSidebarOpen: (_, { open }) => open,
                locationChanged: () => false,
            },
        ],
        // Opening a pane clears the pages, so the back button on the first page returns to the pane.
        mobilePages: [
            [] as TodayMobilePage[],
            {
                setMobilePages: (_, { pages }) => pages,
                setMobileSidebarOpen: (state, { open }) => (open ? [] : state),
                locationChanged: (state, { method, pathname, search, hash }) =>
                    nextMobilePages(state, method, { pathname, url: `${pathname}${search}${hash}` }),
            },
        ],
        // The resizer persists the width itself. This copy lets the app layout size the main column from it.
        sidebarWidth: [TODAY_SIDEBAR_DEFAULT_WIDTH, { setSidebarWidth: (_, { width }) => clampSidebarWidth(width) }],
    }),
    selectors({
        routePane: [
            () => [router.selectors.location],
            (location: { pathname: string }): TodayRailPane | null => railPaneForPath(location.pathname),
        ],
        activePane: [
            (s) => [s.pickedPane, s.routePane, s.mobileNavLayout],
            (
                pickedPane: TodayRailPane | null,
                routePane: TodayRailPane | null,
                mobileNavLayout: boolean
            ): TodayRailPane =>
                pickedPane === 'more' && !mobileNavLayout ? (routePane ?? 'home') : (pickedPane ?? routePane ?? 'home'),
        ],
        leftNavWidth: [
            (s) => [s.sidebarOpen, s.sidebarWidth, s.mobileLayout, s.mobileNavLayout],
            (sidebarOpen: boolean, sidebarWidth: number, mobileLayout: boolean, mobileNavLayout: boolean): number =>
                mobileNavLayout ? 0 : TODAY_RAIL_WIDTH + (sidebarOpen && !mobileLayout ? sidebarWidth : 0),
        ],
        sidebarVisible: [
            (s) => [s.mobileLayout, s.mobileSidebarOpen, s.sidebarOpen],
            (mobileLayout: boolean, mobileSidebarOpen: boolean, sidebarOpen: boolean): boolean =>
                mobileLayout ? mobileSidebarOpen : sidebarOpen,
        ],
        todayRailEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV],
        ],
    }),
    subscriptions(({ actions }) => ({
        mobileLayout: () => actions.setMobileSidebarOpen(false),
    })),
    listeners(({ actions, values, cache }) => ({
        toggleSidebar: () => {
            if (values.mobileLayout) {
                actions.setMobileSidebarOpen(!values.mobileSidebarOpen)
            } else {
                actions.setSidebarOpen(!values.sidebarOpen)
            }
        },
        setMobileSidebarOpen: ({ open }) => {
            if (!open) {
                cache.disposables.dispose('drawerEscape')
                return
            }
            cache.disposables.add(() => {
                const onKeyDown = (event: KeyboardEvent): void => {
                    if (event.key === 'Escape' && values.mobileSidebarOpen) {
                        actions.setMobileSidebarOpen(false)
                    }
                }
                window.addEventListener('keydown', onKeyDown)
                return () => window.removeEventListener('keydown', onKeyDown)
            }, 'drawerEscape')
        },
        goBackOnMobile: () => {
            const previous = values.mobilePages[values.mobilePages.length - 2]
            if (!previous) {
                actions.setMobileSidebarOpen(true)
                return
            }
            actions.setMobilePages(values.mobilePages.slice(0, -1))
            router.actions.replace(previous.url)
        },
        pickPane: ({ pane }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today rail pane picked', { pane, mobile_nav: values.mobileNavLayout })
            if (pane === 'home' && values.routePane !== 'home') {
                router.actions.push(urls.projectHomepage())
            }
            if (pane === 'views' && values.routePane !== 'views') {
                router.actions.push(urls.views())
            }
            if (pane === 'library' && values.routePane !== 'library') {
                router.actions.push(urls.library())
            }
            if (values.mobileLayout) {
                actions.setMobileSidebarOpen(true)
            } else {
                actions.setSidebarOpen(true)
            }
        },
    })),
    afterMount(({ actions }) => {
        const { pathname, search, hash } = router.values.location
        actions.setMobilePages([{ pathname, url: `${pathname}${search}${hash}` }])
    }),
])
